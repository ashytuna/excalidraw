"""
Builds the Excalifont woff2 chunks from DFVN Excalifont (Vietnamese-enabled
derivative of Excalifont by Dafont.vn, SIL OFL 1.1).

Usage (needs fonttools + brotli):
  nix shell --impure --expr 'with import <nixpkgs> {}; python3.withPackages (p: [p.fonttools p.brotli])' \
    -c python3 scripts/dfvn-font/build.py
"""

import hashlib
import io
import os
import re

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "DFVN-Excalifont.ttf")
OUT = os.path.join(HERE, "../../packages/excalidraw/fonts/Excalifont")

# chunk name -> codepoint predicate; evaluated in order, first match wins
VIETNAMESE = (
    set(range(0x1EA0, 0x1EFA))
    | {0x102, 0x103, 0x110, 0x111, 0x128, 0x129, 0x168, 0x169}
    | {0x1A0, 0x1A1, 0x1AF, 0x1B0, 0x20AB}
    | {0x300, 0x301, 0x303, 0x309, 0x323}
)
CHUNKS = [
    ("latin", lambda c: c <= 0xFF or 0x2000 <= c <= 0x206F or c in
        {0x131, 0x152, 0x153, 0x2BC, 0x2C6, 0x2DA, 0x2DC, 0x304, 0x308,
         0x20AC, 0x2122, 0x2212}),
    ("vietnamese", lambda c: c in VIETNAMESE),
    ("cyrillic", lambda c: 0x400 <= c <= 0x4FF or c == 0x2116),
    ("greek", lambda c: 0x370 <= c <= 0x3FF),
    ("latin-ext", lambda c: True),
]


def to_ranges(cps):
    cps = sorted(cps)
    out, start, prev = [], cps[0], cps[0]
    for c in cps[1:] + [None]:
        if c is not None and c == prev + 1:
            prev = c
            continue
        out.append(f"U+{start:x}" if start == prev else f"U+{start:x}-{prev:x}")
        if c is not None:
            start = prev = c
    return ",".join(out)


def main():
    cmap = TTFont(SRC).getBestCmap()
    buckets = {name: [] for name, _ in CHUNKS}
    for cp in cmap:
        for name, pred in CHUNKS:
            if pred(cp):
                buckets[name].append(cp)
                break

    for f in os.listdir(OUT):
        if f.endswith(".woff2"):
            os.remove(os.path.join(OUT, f))

    faces = []
    for name, _ in CHUNKS:
        cps = buckets[name]
        if not cps:
            continue
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.hinting = False
        opts.layout_features = ["*"]
        opts.name_IDs = ["*"]
        opts.notdef_outline = True
        font = TTFont(SRC)
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=cps)
        sub.subset(font)
        buf = io.BytesIO()
        font.flavor = "woff2"
        font.save(buf)
        data = buf.getvalue()
        filename = f"Excalifont-Regular-{hashlib.md5(data).hexdigest()}.woff2"
        with open(os.path.join(OUT, filename), "wb") as fh:
            fh.write(data)
        faces.append((name, filename, to_ranges(cps)))
        print(f"{name:12} {len(cps):4} glyphs {len(data):7} B  {filename}")

    index = os.path.join(OUT, "index.ts")
    src = open(index, encoding="utf-8").read()
    # keep the license comment block
    license_block = re.search(r"/\*.*?\*/", src, re.S).group(0)
    lines = ['import { type ExcalidrawFontFaceDescriptor } from "../Fonts";', ""]
    for i, (_, filename, _) in enumerate(faces):
        lines.append(f'import _{i} from "./{filename}";')
    lines += ["", "/* Generated by scripts/dfvn-font/build.py from DFVN Excalifont",
              "   (Vietnamese glyphs by Dafont.vn), derived from: */", license_block, "",
              "export const ExcalifontFontFaces: ExcalidrawFontFaceDescriptor[] = ["]
    for i, (name, _, ranges) in enumerate(faces):
        lines += [f"  // {name}", "  {", f"    uri: _{i},",
                  f'    descriptors: {{ unicodeRange: "{ranges}" }},', "  },"]
    lines += ["];", ""]
    with open(index, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


if __name__ == "__main__":
    main()
